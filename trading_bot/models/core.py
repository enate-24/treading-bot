"""Core data models for the trading bot system."""

from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal
from typing import Dict, Any, Optional, List
from .enums import SignalDirection, OrderSide, OrderType, TimeInForce


@dataclass
class OHLCV:
    """Open, High, Low, Close, Volume data."""
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: Decimal


@dataclass
class Price:
    """Price data for a trading symbol."""
    symbol: str
    timestamp: datetime
    bid: Decimal
    ask: Decimal
    last: Decimal
    volume: Decimal


@dataclass
class MarketData:
    """Market data with indicators."""
    symbol: str
    timestamp: datetime
    ohlcv: OHLCV
    indicators: Dict[str, float]


@dataclass
class TradingSignal:
    """Trading signal generated by strategy."""
    symbol: str
    direction: SignalDirection
    strength: float  # 0.0 to 1.0
    confidence: float  # 0.0 to 1.0
    timestamp: datetime
    strategy: str
    metadata: Dict[str, Any]


@dataclass
class Position:
    """Trading position information."""
    symbol: str
    quantity: Decimal
    entry_price: Decimal
    current_price: Decimal
    unrealized_pnl: Decimal
    stop_loss: Optional[Decimal]
    take_profit: Optional[Decimal]
    timestamp: datetime


@dataclass
class OrderRequest:
    """Order request for execution."""
    symbol: str
    side: OrderSide
    order_type: OrderType
    quantity: Decimal
    price: Optional[Decimal]
    stop_loss: Optional[Decimal]
    take_profit: Optional[Decimal]
    time_in_force: TimeInForce


@dataclass
class ExecutedTrade:
    """Executed trade information."""
    trade_id: str
    symbol: str
    side: OrderSide
    quantity: Decimal
    price: Decimal
    fee: Decimal
    timestamp: datetime
    order_id: str


@dataclass
class OrderResult:
    """Result of order placement."""
    order_id: str
    status: str
    message: str
    timestamp: datetime


@dataclass
class OrderStatus:
    """Order status information."""
    order_id: str
    symbol: str
    side: OrderSide
    order_type: OrderType
    quantity: Decimal
    filled_quantity: Decimal
    price: Optional[Decimal]
    status: str
    timestamp: datetime


@dataclass
class PortfolioMetrics:
    """Portfolio performance metrics."""
    total_value: Decimal
    available_capital: Decimal
    unrealized_pnl: Decimal
    realized_pnl: Decimal
    positions_count: int
    timestamp: datetime


@dataclass
class RiskMetrics:
    """Risk management metrics."""
    current_drawdown: float
    max_drawdown: float
    daily_pnl: Decimal
    portfolio_risk: float
    position_risk: Dict[str, float]
    timestamp: datetime


@dataclass
class PerformanceReport:
    """Performance analysis report."""
    period: str
    total_trades: int
    winning_trades: int
    losing_trades: int
    win_rate: float
    total_pnl: Decimal
    sharpe_ratio: float
    max_drawdown: float
    profit_factor: float
    timestamp: datetime